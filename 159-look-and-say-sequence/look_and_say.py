"""
Problem 159: Look-and-Say Sequence
Each term is generated by counting consecutive identical digits of the previous term.
"1" -> "11" -> "21" -> "1211" -> "111221"
"""

def next_look_and_say(s: str) -> str:
    """Compute the next term in the look-and-say sequence."""
    if not s:
        return ""
    result = []
    i = 0
    while i < len(s):
        count = 1
        while i + 1 < len(s) and s[i] == s[i + 1]:
            count += 1
            i += 1
        result.append(f"{count}{s[i]}")
        i += 1
    return "".join(result)

def generate_look_and_say(n: int, start: str = "1") -> list[str]:
    """Generate the first n terms of look-and-say sequence."""
    if n <= 0:
        return []
    terms = [start]
    for _ in range(n - 1):
        terms.append(next_look_and_say(terms[-1]))
    return terms

if __name__ == "__main__":
    expected = ["1", "11", "21", "1211", "111221", "312211"]
    assert generate_look_and_say(6) == expected
    assert next_look_and_say("1") == "11"
    assert next_look_and_say("11") == "21"
    print("[PASS] Problem 159: look and say sequence passed all tests.")
